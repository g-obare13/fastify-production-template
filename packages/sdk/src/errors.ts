/**
 * @file Problem Details and typed API error representations for client operations.
 * @module @app/sdk/errors
 */

/**
 * Describes a single invalid request parameter in validation failure responses.
 */
export interface InvalidParam {
  /** JSON pointer or field path of the invalid parameter */
  path: string;
  /** Name of the invalid field or parameter */
  name: string;
  /** Human-readable explanation of why the parameter is invalid */
  reason: string;
}

/**
 * RFC 9457 Problem Details schema returned by error responses.
 */
export interface ProblemDetails {
  /** URI reference identifying the problem type */
  type?: string | undefined;
  /** Short, human-readable summary of the problem type */
  title?: string | undefined;
  /** HTTP status code generated by the origin server */
  status: number;
  /** Human-readable explanation specific to this occurrence of the problem */
  detail?: string | undefined;
  /** URI reference identifying the specific occurrence of the problem */
  instance?: string | undefined;
  /** Stable application error code enum */
  code?: string | undefined;
  /** Injected correlation identifier for log tracing */
  requestId?: string | undefined;
  /** Array of specific invalid request parameters if applicable */
  invalidParams?: InvalidParam[] | undefined;
  /** Additional extension members */
  [key: string]: unknown;
}

/**
 * Standard typed API error representing RFC 9457 Problem Details.
 * Exposes the stable error code, HTTP status, and validation paths.
 */
export class ApiError extends Error {
  /** HTTP response status code */
  readonly status: number;
  /** Stable application error code */
  readonly code: string;
  /** Correlation request identifier */
  readonly requestId?: string;
  /** Detailed field validation failures */
  readonly invalidParams?: InvalidParam[];
  /** Complete RFC 9457 problem payload */
  readonly problem: ProblemDetails;

  /**
   * Constructs an ApiError instance from an RFC 9457 Problem Details payload.
   *
   * @param problem Problem details payload parsed from HTTP response
   */
  constructor(problem: ProblemDetails) {
    super(problem.detail || problem.title || `API error: status ${problem.status}`);
    this.name = 'ApiError';
    this.status = problem.status;
    this.code = problem.code || 'UNKNOWN_ERROR';
    if (problem.requestId !== undefined) this.requestId = problem.requestId;
    if (problem.invalidParams !== undefined) this.invalidParams = problem.invalidParams;
    this.problem = problem;
  }
}
